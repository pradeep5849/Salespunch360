import fs from "node:fs";
import path from "node:path";
import postcss from "postcss";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
function sources(directory) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const name = path.join(directory, entry.name);
    return entry.isDirectory()
      ? sources(name)
      : /\.(tsx?|css)$/.test(name) &&
          !/\.test\./.test(name) &&
          !name.endsWith("public-shared.css")
        ? [fs.readFileSync(name, "utf8")]
        : [];
  });
}
// Keep every selector whose class names can occur in public components, including
// responsive/state classes. This deliberately retains tag rules, variables,
// keyframes and conservative false positives rather than changing the cascade.
const publicSource = [
  ...sources(path.join(root, "src/app/(marketing)")),
  ...sources(path.join(root, "src/components/public")),
  ...[
    "src/app/error.tsx",
    "src/app/not-found.tsx",
    "src/components/brand-logo.tsx",
    "src/app/pwa-install.tsx",
    "src/app/pwa.css",
  ].map((name) => fs.readFileSync(path.join(root, name), "utf8")),
].join("\n");
const words = new Set(publicSource.match(/[A-Za-z_][\w-]*/g));
const sheets = ["globals.css", "functional-polish.css"].map((name) => {
  const sheet = postcss.parse(
    fs.readFileSync(path.join(root, "src/app", name), "utf8"),
  );
  sheet.walkComments((comment) => comment.remove());
  sheet.walkRules((rule) => {
    const selectors = rule.selectors.filter((selector) =>
      [...selector.matchAll(/\.([A-Za-z_][\w-]*)/g)].every((match) =>
        words.has(match[1]),
      ),
    );
    if (selectors.length) rule.selectors = selectors;
    else rule.remove();
  });
  sheet.walkAtRules((rule) => {
    if (rule.nodes && !rule.nodes.length) rule.remove();
  });
  return sheet.toString().trim();
});
const result =
  "/* Generated by node scripts/public-styles.mjs; edit the source styles instead. */\n" +
  sheets.join("\n") +
  "\n";
const target = path.join(root, "src/app/(marketing)/public-shared.css");
if (process.argv.includes("--check")) {
  if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== result) {
    console.error(
      "Public styles are stale. Run node scripts/public-styles.mjs and commit the result.",
    );
    process.exitCode = 1;
  }
} else {
  fs.writeFileSync(target, result);
  console.info(`Public shared styles: ${Buffer.byteLength(result)} bytes.`);
}
